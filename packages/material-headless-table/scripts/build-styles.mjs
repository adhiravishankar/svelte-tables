// Builds src/lib/styles.css from the prebuilt `bare.css` of each SMUI package.
//
// SMUI 9 only exposes its Sass entry points through `exports`, so the CSS cannot
// be imported by name. The files are on disk, though, so they are read directly
// and concatenated into one stylesheet that ships as `material-svelte-headless-table/styles.css`.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));

// pnpm keeps dependencies next to the package, npm hoists them to the workspace root.
function findInNodeModules(path) {
  for (let dir = root; dir !== dirname(dir); dir = dirname(dir)) {
    const file = join(dir, 'node_modules', path);
    if (existsSync(file)) return file;
  }
  return join(root, 'node_modules', path);
}

const packages = [
  'button',
  'checkbox',
  'form-field',
  'icon-button',
  'list',
  'menu',
  'menu-surface',
  'switch',
  'textfield',
];

const header = `/*
 * Base styles for the SMUI components Material Headless Table is built on.
 * Generated by scripts/build-styles.mjs - do not edit.
 *
 * Import this once in your app:
 *
 *   import 'material-svelte-headless-table/styles.css';
 *
 * The components read the standard Material theme variables with sensible
 * fallbacks, so you can theme the table by defining any of these on :root (or
 * any ancestor): --mdc-theme-primary, --mdc-theme-secondary,
 * --mdc-theme-surface, --mdc-theme-on-surface, --mdc-theme-on-primary.
 */
`;

const seen = new Set();
const parts = [header];
for (const name of packages) {
  const file = findInNodeModules(join('@smui', name, 'bare.css'));
  if (!existsSync(file)) throw new Error(`@smui/${name} has no bare.css`);
  const css = readFileSync(file, 'utf8').trim();
  if (seen.has(css)) continue;
  seen.add(css);
  parts.push(`/* @smui/${name} */\n${css}\n`);
}

const out = join(root, 'src/lib/styles.css');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, parts.join('\n'));
console.log(
  `styles.css: ${packages.length} packages, ${(parts.join('\n').length / 1024).toFixed(0)} KB`,
);
