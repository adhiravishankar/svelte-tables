// Generates the API reference pages from the library's own source, so they can
// not drift from the code:
//  - option / column / state names, types and doc comments come from `types.ts`
//  - defaults come from the destructuring in `defineTableOptions` (`tableOptions.ts`)
//
// Output goes to src/content/docs/api/*.mdx (git-ignored, regenerated on dev/build).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const lib = join(root, '../../packages/shadcn-tanstack-table/src/lib');
const outDir = join(root, 'src/content/docs/api');
mkdirSync(outDir, { recursive: true });

const read = (file) =>
  ts.createSourceFile(
    file,
    readFileSync(file, 'utf8'),
    ts.ScriptTarget.Latest,
    true,
  );

const types = read(join(lib, 'types.ts'));
const optionsSource = read(join(lib, 'tableOptions.ts'));

const oneLine = (text) => text.replace(/\s+/g, ' ').trim();

/** Defaults from `const { a = 1, b = false, ...rest } = options` in defineTableOptions. */
function readDefaults() {
  const defaults = {};
  const visit = (node) => {
    if (
      ts.isFunctionLike(node) &&
      node.name === undefined &&
      ts.isVariableDeclaration(node.parent)
    ) {
      // arrow function assigned to a const
    }
    if (
      ts.isVariableDeclaration(node) &&
      ts.isObjectBindingPattern(node.name) &&
      node.initializer &&
      ts.isIdentifier(node.initializer) &&
      node.initializer.text === 'options'
    ) {
      for (const element of node.name.elements) {
        if (element.initializer && ts.isIdentifier(element.name)) {
          defaults[element.name.text] = oneLine(element.initializer.getText());
        }
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(optionsSource);
  return defaults;
}
const defaults = readDefaults();

/** A property's doc comment, as one paragraph. */
function docOf(node) {
  const docs = node.jsDoc;
  if (!docs?.length) return '';
  const comment = docs
    .map((d) =>
      typeof d.comment === 'string'
        ? d.comment
        : (ts.getTextOfJSDocComment(d.comment) ?? ''),
    )
    .join('\n');
  return oneLine(comment);
}

function interfaceMembers(name) {
  let found;
  ts.forEachChild(types, (node) => {
    if (ts.isInterfaceDeclaration(node) && node.name.text === name)
      found = node;
  });
  if (!found) throw new Error(`Interface ${name} not found in types.ts`);
  return found.members
    .filter(ts.isPropertySignature)
    .map((member) => ({
      doc: docOf(member),
      name: member.name.getText(),
      optional: !!member.questionToken,
      type: oneLine(member.type?.getText(types) ?? 'unknown'),
    }))
    .sort((a, b) =>
      a.name.localeCompare(b.name, 'en', { sensitivity: 'base' }),
    );
}

// MDX treats `{` and `<` as syntax, `|` ends a table cell: keep text safe.
const code = (text) =>
  '`' + text.replace(/\|/g, '\\|').replace(/`/g, "'") + '`';
const prose = (text) =>
  text.replace(/\|/g, '\\|').replace(/[{}<>]/g, (c) => `\\${c}`);

function table(members, { withDefaults }) {
  const head = withDefaults
    ? '| Option | Type | Default | Description |\n| --- | --- | --- | --- |'
    : '| Name | Type | Description |\n| --- | --- | --- |';
  const rows = members.map((m) => {
    const name = code(m.name + (m.optional ? '?' : ''));
    const type = code(
      m.type.length > 160 ? m.type.slice(0, 157) + '…' : m.type,
    );
    const doc = prose(m.doc);
    if (!withDefaults) return `| ${name} | ${type} | ${doc} |`;
    const def = defaults[m.name] !== undefined ? code(defaults[m.name]) : '';
    return `| ${name} | ${type} | ${def} | ${doc} |`;
  });
  return `${head}\n${rows.join('\n')}\n`;
}

const page = ({ title, description, order, intro, body }) => `---
title: ${title}
description: ${description}
sidebar:
  order: ${order}
---

{/* Generated by scripts/generate-api.mjs from the library source. Do not edit. */}

${intro}

${body}`;

function write(file, content) {
  writeFileSync(join(outDir, file), content);
}

const tableOptions = interfaceMembers('MRT_TableOptions');
write(
  'table-options.mdx',
  page({
    body: table(tableOptions, { withDefaults: true }),
    description:
      'Every option of createShadcnSvelteTable and the ShadcnSvelteTable component.',
    intro: `Options for \`createShadcnSvelteTable\` and \`<ShadcnSvelteTable options={…} />\`. Only \`columns\` and \`data\`
are required.

Anything reactive (\`data\`, \`state\`, …) must be passed as a [getter](/getting-started/usage/#reactive-options).
\`…Props\` options take an object, or a function of their context. Options named after a former \`render…\` option are
snippets.

This lists the options MRT adds or changes. The table also accepts the [TanStack Table v9
options](https://tanstack.com/table/latest/docs/api/core/table) of the enabled features, such as \`enableSorting\`,
\`manualPagination\`, \`getRowId\` or \`filterFromLeafRows\`.`,
    order: 1,
    title: 'Table Options',
  }),
);

const columnOptions = interfaceMembers('MRT_ColumnDef');
write(
  'column-options.mdx',
  page({
    body: table(columnOptions, { withDefaults: false }),
    description: 'Every option of a column definition.',
    intro: `Options of a column definition (\`MRT_ColumnDef\`). A data column needs \`header\` and an \`accessorKey\`, or an
\`accessorFn\` plus an \`id\`. Capitalized options (\`Cell\`, \`Header\`, …) are snippets.

Column definitions also accept the TanStack Table v9 column options of the enabled features, such as \`enableSorting\`,
\`enableHiding\`, \`size\` or \`aggregationFn\`.`,
    order: 2,
    title: 'Column Options',
  }),
);

const stateMembers = interfaceMembers('MRT_TableState');
write(
  'state.mdx',
  page({
    body: table(stateMembers, { withDefaults: false }),
    description: 'The state MRT adds to the TanStack Table state.',
    intro: `State that Shadcn Svelte Table owns, available as \`table.mrtState\`, in \`initialState\` and (as getters) in
\`state\`. See [State Management](/guides/state-management/).

Everything else (sorting, filters, pagination, selection, …) is TanStack Table state, read with
\`table.atoms.<slice>.get()\`. \`initialState\` and \`state\` accept both kinds.`,
    order: 3,
    title: 'State',
  }),
);

